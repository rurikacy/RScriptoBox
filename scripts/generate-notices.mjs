import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = path => JSON.parse(readFileSync(path, 'utf8').replace(/^\uFEFF/, ''));
const manifest = readJson(join(root, 'package.json'));
const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--manifest-path', 'src-tauri/Cargo.toml', '--format-version', '1', '--locked', '--offline', '--filter-platform', 'x86_64-pc-windows-msvc'], { cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }));
const nodes = new Map(metadata.resolve.nodes.map(node => [node.id, node]));
const reachable = new Set();
function visit(id) {
  if (reachable.has(id)) return;
  reachable.add(id);
  for (const dependency of nodes.get(id)?.dependencies ?? []) visit(dependency);
}
visit(metadata.resolve.root);

function notices(directory, explicit) {
  const paths = new Set();
  function scan(folder, licenseDirectory = false) {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      const path = join(folder, entry.name);
      if (entry.isFile() && (licenseDirectory || /^(licen[sc]e|copying|copyright|notice|unlicense|third.party)([._-]|$)/i.test(entry.name))) paths.add(path);
      if (entry.isDirectory() && /^(licenses?|legal|notices?)$/i.test(entry.name)) scan(path, true);
    }
  }
  scan(directory);
  if (explicit && existsSync(resolve(directory, explicit))) paths.add(resolve(directory, explicit));
  return [...paths].sort().map(path => `--- ${relative(directory, path).replaceAll('\\', '/')} ---\n${readFileSync(path, 'utf8').trim()}\n`).join('\n');
}

const sections = [];
const missing = [];
const supplementalPath = join(root, 'docs/licenses/supplemental.json');
const supplemental = existsSync(supplementalPath) ? readJson(supplementalPath) : {};
function add(ecosystem, name, version, license, source, directory, explicit) {
  const supplement = supplemental[`${ecosystem}:${name}@${version}`];
  const texts = notices(directory, explicit) || (supplement ? readFileSync(join(root, 'docs/licenses', supplement), 'utf8') : '');
  if (!texts) missing.push(`${ecosystem}: ${name}@${version}`);
  const archive = ecosystem === 'Rust' ? `Source archive: https://crates.io/api/v1/crates/${name}/${version}/download\n` : '';
  sections.push(`${'='.repeat(72)}\n${ecosystem}: ${name} ${version}\nDeclared license: ${license || 'Not declared'}\nSource: ${source}\n${archive}\n${texts || 'No standalone license text was found in the installed package. Consult the versioned source above.\n'}`);
}

for (const pkg of metadata.packages.filter(pkg => pkg.source && reachable.has(pkg.id)).sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`))) {
  add('Rust', pkg.name, pkg.version, pkg.license, `https://crates.io/crates/${pkg.name}/${pkg.version}`, dirname(pkg.manifest_path), pkg.license_file);
}
const lock = readJson(join(root, 'package-lock.json'));
const omitted = [];
for (const [path, pkg] of Object.entries(lock.packages).filter(([path]) => path).sort(([a], [b]) => a.localeCompare(b))) {
  const directory = join(root, path);
  if (!existsSync(join(directory, 'package.json'))) { omitted.push(`${path}@${pkg.version}`); continue; }
  const installed = readJson(join(directory, 'package.json'));
  if (installed.version !== pkg.version) throw new Error(`Run npm ci: version mismatch for ${path}`);
  add('npm', installed.name, installed.version, installed.license || pkg.license, `https://www.npmjs.com/package/${installed.name}/v/${installed.version}`, directory);
}

const header = `RScriptoBox ${manifest.version} — dependency license inventory\n\nGenerated by scripts/generate-notices.mjs from local locked packages.\nRust scope: reachable dependencies for x86_64-pc-windows-msvc, including build tools.\nnpm scope: installed packages in package-lock.json, including development tools.\nThis is a source/build inventory, not proof that every listed package is linked into the EXE.\nOriginal notice text is reproduced below; third-party terms are not replaced by the project license.\nExternal Python, PowerShell, WinGet and WebView2 installations are not included.\n\nMissing standalone texts: ${missing.length}\n${missing.join('\n')}\n\nPlatform-optional npm packages not installed on this host: ${omitted.length}\n${omitted.join('\n')}\n\n`;
const output = join(root, 'docs/licenses/dependencies.txt');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, header + sections.join('\n'), 'utf8');
console.log(`Wrote ${sections.length} package records. Missing standalone texts: ${missing.length}.`);
if (missing.length) console.log(missing.join('\n'));
